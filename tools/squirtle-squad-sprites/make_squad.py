"""Overlay Squirtle Squad shades on every frame of the Squirtle sprite.

Styles (from "Here Comes the Squirtle Squad", EP012):
  leader  the boss's pointed shades: two black triangular lenses meeting at a
          thick bridge, top edge flat across the near lens, outer tips pointed,
          pale lavender glare. In 3/4 view the far lens tip sticks up past the head.
  member  the squad members' round shades: navy lenses with a thin black rim, a
          pale highlight in the upper left, a small glint lower down, and a thin
          bridge; the lenses nearly touch.

Usage: python3 -I make_squad.py <leader|member> <src.gif> <out.gif> [<preview_dir>]
Stamps are drawn in frame-0 coordinates. Each lens follows the motion of its
half of the head, measured per frame, so the shades bob and tilt with the head.
"""
import math
import sys
from PIL import Image, ImageSequence

K = (16, 16, 16, 255)     # black (same black as the sprite's outline)
SKIN = (140, 198, 206, 255)
SKIN_SHADE = (90, 156, 165, 255)

# Every stamp row string starts at x = 3; '.' leaves the sprite alone.
STAMP_X0 = 3
STYLES = {
    "leader": {
        # Generated by refgrid.py from an anime frame of the leader in 3/4 view, with
        # the bridge anchored between the sprite's eyes (see refgrid.py ANCHORS) and
        # glare on the outer rim turned black.
        "stamp": {
            7:  ".KKK",
            8:  "..KKK",
            9:  "..KKKK",
            10: "..KKKKK",
            11: "..KKKGGKKKKKKKKKKKKKK",
            12: "...KGGKKKKKKKGGGKKKK",
            13: "...KKKKKKKKKGGGKKKK",
            14: "....KKKKKKKGGGKKKKK",
            15: "....KKK....KKKKKKK",
            16: ".............KKK",
        },
        "colors": {"K": K, "G": (184, 192, 216, 255)},  # glare sampled from the episode
        "far_last": 9, "near_first": 14,  # lens columns; the bridge lies between
        "bridge_rows": (11, 14),
    },
    "member": {
        # Sized and placed from the members in EP012: lenses ~8px (their height runs
        # from about a third of the way down the head to just above the mouth), bridge
        # at x=11 like the leader's, far lens squeezed to ~half width for the 3/4 view
        # and kept clear of the snout highlight at (5-6, 15-16).
        "stamp": {
            9:  "....KKK....KKKK",
            10: "...KHHNK..KHHHNK",
            11: "...KHNNK.KHHHHNNK",
            12: "...KNNNKKKHNNNNNK",
            13: "...KNNNK.KNNWNNNK",
            14: "...KNNNK.KNWNNNNK",
            15: "....KKK...KNNNNK",
            16: "...........KKKK",
        },
        "colors": {
            "K": K,
            "N": (32, 40, 104, 255),    # lens navy, sampled from the episode
            "H": (210, 230, 232, 255),  # highlight, sampled from the episode
            "W": (248, 252, 255, 255),  # glint (off-white: pure white marks eye pixels)
        },
        "far_last": 10, "near_first": 12,
        "bridge_rows": (12, 12),
    },
}

EYE = {(132, 41, 0), (214, 206, 206), (255, 255, 255)}
# Eye pixels the lenses don't cover get painted over with skin.
ERASE = {(132, 41, 0), (214, 206, 206), (255, 255, 255), (16, 16, 16), (41, 115, 132)}
FAR_COLS, NEAR_COLS = range(0, 11), range(12, 25)  # far / near half of the head

for _s in STYLES.values():
    _top, _bottom = _s["bridge_rows"]
    assert all(_s["stamp"][y][x - STAMP_X0] == "K" for y in range(_top, _bottom + 1)
               for x in range(_s["far_last"] + 1, _s["near_first"])), "bridge must be solid black"


def bbox(pts):
    return min(p[0] for p in pts), min(p[1] for p in pts), max(p[0] for p in pts), max(p[1] for p in pts)


def eyes(f):
    top = min(y for y in range(f.height) for x in range(8, 20) if f.getpixel((x, y))[3])
    rows = range(top + 4, top + 13)
    near = [(x, y) for y in rows for x in range(11, 24) if f.getpixel((x, y))[:3] in EYE]
    far = [(x, y) for y in rows for x in range(3, 11) if f.getpixel((x, y))[:3] in EYE]
    return bbox(near), bbox(far)


def is_interior(f, x, y):
    return all(f.getpixel((x + dx, y + dy))[3] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))


def px(f, x, y):
    if 0 <= x < f.width and 0 <= y < f.height:
        p = f.getpixel((x, y))
        return p[:3] if p[3] else None
    return None


def head_move(f0, f, cols):
    """Best (dx, dy) aligning frame 0's head (rows above the mouth) in these columns onto f."""
    region = [(x, y) for y in range(0, 17) for x in cols]

    def err(dx, dy):
        bad = n = 0
        for x, y in region:
            a, b = px(f0, x, y), px(f, x + dx, y + dy)
            if a is None and b is None:
                continue
            n += 1
            bad += a != b
        return bad / n

    return min(((err(dx, dy), dx, dy) for dx in range(-3, 4) for dy in range(-6, 4)))[1:]


def stamp(f, f0, style):
    s = STYLES[style]
    out = f.copy()
    (nx0, ny0, nx1, ny1), (fx0, fy0, fx1, fy1) = eyes(f)
    # Near eye (plus its dark right rim) and far eye (plus the black pixel under it).
    for x in range(nx0, nx1 + 2):
        for y in range(ny0, ny1 + 1):
            if out.getpixel((x, y))[:3] in ERASE and is_interior(f, x, y):
                out.putpixel((x, y), SKIN if x < nx0 + 3 else SKIN_SHADE)
    for x in range(fx0, fx1 + 1):
        for y in range(fy0, fy1 + 2):
            if out.getpixel((x, y))[:3] in ERASE and is_interior(f, x, y):
                out.putpixel((x, y), SKIN_SHADE)
    # In frames 19-27 the head tilts: the far side rises and shifts more than the
    # near side. Each lens follows its own half so the shades tilt with the head
    # instead of sliding as one rigid block.
    far, near = head_move(f0, f, FAR_COLS), head_move(f0, f, NEAR_COLS)
    far_last, near_first = s["far_last"], s["near_first"]

    def put(x, y, color):
        if 0 <= x < out.width and 0 <= y < out.height:
            out.putpixel((x, y), color)

    for y, row in s["stamp"].items():
        for i, c in enumerate(row):
            sx = STAMP_X0 + i
            if c == "." or far_last < sx < near_first:
                continue
            dx, dy = far if sx <= far_last else near
            put(sx + dx, y + dy, s["colors"][c])
    # Bridge: redrawn to join the lenses, its rows blended between their offsets.
    # A thick bridge rounds outward so a 1px difference never leaves a dent; a
    # one-row bridge rounds to the nearest row so it stays one pixel thick.
    top, bottom = s["bridge_rows"]
    left, right = far_last + far[0], near_first + near[0]
    for x in range(left + 1, right):
        dy = far[1] + (near[1] - far[1]) * (x - left) / (right - left)
        if top == bottom:
            rows = [math.floor(top + dy + 0.5)]
        else:
            rows = range(math.floor(top + dy), math.ceil(bottom + dy) + 1)
        for y in rows:
            put(x, y, K)
    return out


def to_palette(frames):
    colors = sorted({p[:3] for f in frames for p in f.get_flattened_data() if p[3]})
    assert len(colors) < 255, len(colors)
    index = {c: i for i, c in enumerate(colors)}
    t = len(colors)
    pal = [v for c in colors for v in c] + [0, 0, 0]
    out = []
    for f in frames:
        p = Image.new("P", f.size, t)
        p.putpalette(pal)
        p.putdata([index[px[:3]] if px[3] else t for px in f.get_flattened_data()])
        out.append(p)
    return out, t


def main(style, src, dst, preview=None):
    im = Image.open(src)
    # The iterator re-seeks one Image object, so copy each frame while iterating.
    raw = [(fr.info.get("duration", 100), fr.convert("RGBA")) for fr in ImageSequence.Iterator(im)]
    durations = [d for d, _ in raw]
    frames = [stamp(f, raw[0][1], style) for _, f in raw]
    pframes, t = to_palette(frames)
    pframes[0].save(dst, save_all=True, append_images=pframes[1:], duration=durations,
                    loop=0, disposal=2, transparency=t, optimize=False)
    if preview:
        S = 8
        W_, H_ = im.size
        sheet = Image.new("RGBA", (W_ * S * 10 + 90, H_ * S * 3 + 30), (49, 51, 56, 255))
        for i, f in enumerate(frames):
            sheet.alpha_composite(f.resize((W_ * S, H_ * S), Image.Resampling.NEAREST), ((i % 10) * (W_ * S + 9), (i // 10) * (H_ * S + 10)))
        sheet.save(f"{preview}/{style}_sheet.png")
        frames[0].resize((W_ * 12, H_ * 12), Image.Resampling.NEAREST).save(f"{preview}/{style}_frame0.png")


if __name__ == "__main__":
    main(*sys.argv[1:])
